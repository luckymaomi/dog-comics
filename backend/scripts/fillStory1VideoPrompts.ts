function main() {
  const db = new Database(dbPath);
  initializeDatabase(db);
  const episode = db
    .prepare(
      `SELECT e.id AS episode_id, d.id AS drama_id, d.title
       FROM episodes e JOIN dramas d ON d.id = e.drama_id
       ORDER BY d.id, e.episode_number LIMIT 1`,
    )
    .get() as { episode_id: number; drama_id: number; title: string } | undefined;
  if (!episode) {
    console.error("没有找到项目/话");
    process.exit(1);
  }

  const panels = db
    .prepare(
      `SELECT id, panel_number, title FROM panels WHERE episode_id = ? ORDER BY panel_number`,
    )
    .all(episode.episode_id) as Array<{
    id: number;
    panel_number: number;
    title: string | null;
  }>;

  const update = db.prepare(
    `UPDATE panels SET video_prompt = ?, updated_at = ? WHERE id = ?`,
  );
  const now = new Date().toISOString();
  let written = 0;
  for (const panel of panels) {
    const text = PROMPTS[panel.panel_number];
    if (!text) continue;
    update.run(text, now, panel.id);
    written += 1;
    console.log(
      `已写入镜 ${panel.panel_number} id=${panel.id} title=${panel.title ?? ""} (${text.length} 字)`,
    );
  }
  console.log(
    `完成：项目「${episode.title}」episode=${episode.episode_id}，写入 ${written}/${panels.length} 镜`,
  );
  db.close();
}

main();
